"""
Example 01: Variables and Data Types
====================================

Learn how to create and use variables in Python.
"""

# String variables
name = "Alice"
city = "New York"
email = "alice@example.com"

print("=== Strings ===")
print(name)
print(city)
print(email)

# Integer variables
age = 25
year = 2026
temperature = -5

print("\n=== Integers ===")
print(age)
print(year)
print(temperature)

# Float variables
height = 5.7
price = 19.99
pi = 3.14159

print("\n=== Floats ===")
print(height)
print(price)
print(pi)

# Boolean variables
is_student = True
is_active = False
has_license = True

print("\n=== Booleans ===")
print(is_student)
print(is_active)
print(has_license)

# None - special "no value"
result = None

print("\n=== None ===")
print(result)

# Checking types
print("\n=== Data Types ===")
print(f"type(name) = {type(name)}")
print(f"type(age) = {type(age)}")
print(f"type(height) = {type(height)}")
print(f"type(is_student) = {type(is_student)}")
print(f"type(result) = {type(result)}")
